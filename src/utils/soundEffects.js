/**
 * Trigger Apple-style elegant confetti burst
 */
export function triggerConfetti() {
  try {
    if (typeof confetti === 'function') {
      confetti({
        particleCount: 80,
        spread: 70,
        origin: { y: 0.6 },
        colors: ['#0071e3', '#34c759', '#ff9500', '#ff3b30', '#af52de', '#5856d6']
      });
    }
  } catch {}
}

/**
 * Trigger massive podium grand confetti
 */
export function triggerPodiumConfetti() {
  try {
    if (typeof confetti === 'function') {
      const end = Date.now() + 3.5 * 1000;
      const colors = ['#ffd700', '#c0c0c0', '#cd7f32', '#0071e3', '#34c759'];
      (function frame() {
        confetti({
          particleCount: 5,
          angle: 60,
          spread: 55,
          origin: { x: 0 },
          colors
        });
        confetti({
          particleCount: 5,
          angle: 120,
          spread: 55,
          origin: { x: 1 },
          colors
        });
        if (Date.now() < end) {
          requestAnimationFrame(frame);
        }
      })();
    }
  } catch {}
}
